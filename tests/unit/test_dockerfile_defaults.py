"""The opt-in Docker build arguments leave a plain ``docker build`` unchanged.

``deploy/docker/Dockerfile`` and ``deploy/docker/mock-cmms/Dockerfile`` take
``PYTHON_BASE`` and ``MACHINA_CONSTRAINTS``, and the deploy image also takes
``TORCH_INDEX_URL``. With every argument at its default, each image must run
the install command it ran before the arguments existed. The real-build
``pip freeze`` comparison is recorded outside the repository; this test pins
the Dockerfile text it depends on.
"""

from __future__ import annotations

import re
from pathlib import Path

_DOCKER = Path(__file__).resolve().parents[2] / "deploy" / "docker"
_DEPLOY = _DOCKER / "Dockerfile"
_MOCK = _DOCKER / "mock-cmms" / "Dockerfile"

_BASE = "python:3.11-slim-bookworm"
# The install commands both Dockerfiles ran before the build arguments existed.
_DEPLOY_INSTALL = 'pip install --no-cache-dir ".[${MACHINA_EXTRAS}]"'
_MOCK_INSTALL = "pip install --no-cache-dir fastapi uvicorn"
_CONSTRAINED = re.compile(
    r'if \[ -n "\$MACHINA_CONSTRAINTS" \]; then (?P<pinned>.+?); else (?P<default>.+?); fi'
)


def _instructions(path: Path) -> list[tuple[str, str]]:
    """Return ``(KEYWORD, arguments)`` per instruction, continuation lines joined."""
    instructions: list[tuple[str, str]] = []
    current = ""
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.endswith("\\"):
            current += line[:-1] + " "
            continue
        keyword, _, arguments = (current + line).partition(" ")
        instructions.append((keyword.upper(), re.sub(r"\s+", " ", arguments).strip()))
        current = ""
    return instructions


def _args(path: Path) -> dict[str, str]:
    """Return each ``ARG`` with its default ('' when declared empty)."""
    found = {}
    for keyword, arguments in _instructions(path):
        if keyword == "ARG":
            name, _, default = arguments.partition("=")
            found[name] = default
    return found


def _install(path: Path) -> re.Match[str]:
    """Return the install step that branches on ``MACHINA_CONSTRAINTS``."""
    runs = [a for k, a in _instructions(path) if k == "RUN" and _CONSTRAINED.fullmatch(a)]
    assert len(runs) == 1, f"{path.name}: one install step branches on MACHINA_CONSTRAINTS"
    match = _CONSTRAINED.fullmatch(runs[0])
    assert match
    return match


def test_build_arguments_default_to_todays_build() -> None:
    assert _args(_DEPLOY) == {
        "PYTHON_BASE": _BASE,
        "MACHINA_EXTRAS": "cmms-rest,mcp",
        "MACHINA_CONSTRAINTS": "",
        "TORCH_INDEX_URL": "",
    }
    # The mock CMMS image installs no torch, so it takes no torch argument.
    assert _args(_MOCK) == {"PYTHON_BASE": _BASE, "MACHINA_CONSTRAINTS": ""}


def test_every_stage_starts_from_the_base_argument() -> None:
    for path in (_DEPLOY, _MOCK):
        instructions = _instructions(path)
        assert instructions[0] == ("ARG", f"PYTHON_BASE={_BASE}"), f"{path.name}: ARG before FROM"
        froms = [arguments for keyword, arguments in instructions if keyword == "FROM"]
        assert froms, path.name
        assert all(re.fullmatch(r"\$\{PYTHON_BASE\}( AS \w+)?", f) for f in froms), froms


def test_default_install_commands_are_unchanged() -> None:
    for path, default in ((_DEPLOY, _DEPLOY_INSTALL), (_MOCK, _MOCK_INSTALL)):
        match = _install(path)
        assert match["default"] == default
        pinned = default.replace("--no-cache-dir", '--no-cache-dir -c "$MACHINA_CONSTRAINTS"')
        assert match["pinned"] == pinned


def test_constraints_files_are_in_each_build_context() -> None:
    # The deploy image builds from the repository root, the mock CMMS image from its folder.
    copies = {
        _DEPLOY: "deploy/docker/constraints.txt ./",
        _MOCK: "constraints.txt ./",
    }
    for path, copy in copies.items():
        assert ("COPY", copy) in _instructions(path), f"{path.name} copies its constraints file"
    for constraints in (_DOCKER / "constraints.txt", _DOCKER / "mock-cmms" / "constraints.txt"):
        header = constraints.read_text(encoding="utf-8").splitlines()[:2]
        assert header[0] == "# This file was autogenerated by uv via the following command:"
        assert header[1].startswith("#    uv pip compile --universal"), header[1]


def test_torch_index_step_is_a_no_op_by_default() -> None:
    instructions = _instructions(_DEPLOY)
    runs = [a for k, a in instructions if k == "RUN"]
    torch = [run for run in runs if "TORCH_INDEX_URL" in run]
    assert len(torch) == 1
    step = torch[0]
    assert step.startswith('if [ -n "$TORCH_INDEX_URL" ]; then ') and step.endswith("; fi")
    assert "else" not in step
    # One index only, so neither the CUDA build nor a shadowing package can come from
    # PyPI; dependencies still resolve from PyPI in the extras install that follows.
    assert '--index-url "$TORCH_INDEX_URL"' in step and "--extra-index-url" not in step
    assert "--no-deps" in step and step.count("torch torchvision") == 1
    assert runs.index(step) < runs.index(next(r for r in runs if "MACHINA_EXTRAS" in r))
